        public override void WriteHeader(BinaryWriter writer)
        {
            base.WriteHeader(writer);
            writer.Write((byte)LanguageLetter);

            StringAmount = (uint)Values.Count;
            writer.Write(StringAmount);
            writer.Write(Modulo);

