        public override string ToString()
        {
            return $"FE Language: {LanguageLetter}";
        }

        public override string? ToDetails()
        {
            StringBuilder Lines = new();

            Lines.AppendLine($"Frontend Language: {Name}");
            Lines.AppendLine($"LanguageLetter: {LanguageLetter}");
            Lines.AppendLine($"Strings Amount: {StringAmount}");
            Lines.AppendLine($"Modulo: {Modulo}");
            Lines.AppendLine($"Dictionary (key: value)");
            //Lines.AppendLine($"Buffer: {Buffer}");
            foreach (var pair in Values)
            {
                if (GlobalHashDicts.ContainsKey(Modulo) && GlobalHashDicts[Modulo].ContainsKey(pair.Key))
                    Lines.AppendLine($"{GlobalHashDicts[Modulo][pair.Key]}: {pair.Value}");
                else
                    Lines.AppendLine($"{pair.Key}: {pair.Value}");
            }

            //Console.WriteLine($"Hash: {GetHash("pause")}");
            //Console.WriteLine($"Hash of loading2: {GetHash("loading2")}");
            //Console.WriteLine($"Hash of loading3: {GetHash("loading3")}");
            //Console.WriteLine($"Hash of loading4: {GetHash("loading4")}");

            return Lines.ToString();
        }

        public uint GetHash(string name)
        {
            uint Hash = 0;

            for (int i = 0; i < name.Length; i++)
            {
                Hash = (64 * Hash + name[i]) % Modulo;
            }

            return Hash;
        }

        public string GetString(uint hash)
        {
            if (Values.ContainsKey(hash))
                return Values[hash];

            return string.Empty;
        }

        private static string Substring(string buffer, int startAt)
        {
            int endIn = startAt;
            for (int i = startAt; i < buffer.Length; i++)
            {
                if (buffer[i] == '\0')
                {
                    endIn = i;
                    break;
                }
            }

            if (startAt == endIn)
                return string.Empty;

            return buffer.Substring(startAt, endIn - startAt);
        }

